import { change as row } from "@antumbra/domain-changes/rows/change.ts";
import { bucket } from "@shivaedev/changes/buckets.ts";
import { collection } from "@shivaedev/changes/keys.ts";
import { makeRepository } from "@shivaedev/sql/repository.ts";
import { Schema } from "effect";
import { Model } from "effect/schema";
import { field } from "#records/field.ts";

class Stored extends Model.Class<Stored>("change")({
	id: row.fields.id,
	repoId: field(bucket(row.fields.repoId)),
	host: field(row.fields.host),
	title: field(row.fields.title),
	body: field(row.fields.body),
	headRef: field(row.fields.headRef),
	baseRef: field(row.fields.baseRef),
	headSha: field(row.fields.headSha),
	preparedHeadRef: field(row.fields.preparedHeadRef),
	preparedHeadSha: field(row.fields.preparedHeadSha),
	publicationRequestId: field(row.fields.publicationRequestId),
	publicationError: field(row.fields.publicationError),
	proposalFrozenAt: field(row.fields.proposalFrozenAt),
	worktreePath: field(row.fields.worktreePath),
	workingDiff: field(row.fields.workingDiff),
	workingTreeStatus: field(row.fields.workingTreeStatus),
	submissionKey: field(row.fields.submissionKey),
	stage: field(row.fields.stage),
	draftAt: field(row.fields.draftAt),
	url: field(row.fields.url),
	externalId: field(row.fields.externalId),
	checks: field(row.fields.checks),
	review: field(row.fields.review),
	mergeable: field(row.fields.mergeable),
	openedByAgentId: field(row.fields.openedByAgentId),
	originSessionId: field(row.fields.originSessionId),
	raw: field(row.fields.raw),
	activityAt: field(row.fields.activityAt),
	observedAt: field(row.fields.observedAt),
	landedAt: field(row.fields.landedAt),
	withdrawnAt: field(row.fields.withdrawnAt),
	archivedAt: field(row.fields.archivedAt),
	createdAt: field(row.fields.createdAt),
	storage_order: Model.GeneratedByDb(Schema.Unknown),
}) {}
export const repository = makeRepository(Stored, {
	tableName: "change",
	idColumn: "id",
	spanPrefix: "change",
	collection: collection("change", Schema.String, { repoId: Schema.String }),
});

